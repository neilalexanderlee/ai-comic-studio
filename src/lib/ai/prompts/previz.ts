/**
 * 白模预演（previz）提示词。
 *
 * 预演要回答的只有一个问题：**这个镜头的机位、运镜和走位对不对。**
 * 材质、颜色、光影、表情全部是干扰项 —— 它们不但不帮忙，还会让人把注意力放到
 * "这张脸像不像"上，从而错过真正要验收的东西。所以这里把画面强行压成灰白模型。
 *
 * 实现上是在正式提示词外面**首尾各夹一段渲染模式覆盖**：扩散/视频模型对开头和结尾的
 * 指令都更敏感，只放一处经常压不住正文里大量的材质与光影描写。
 */

/** 白模渲染的风格标签，用来顶掉项目原本的 visualStyleTag */
export const PREVIZ_STYLE_TAG =
  "灰白模预演渲染（clay render / grey box），无材质无纹理无贴图，" +
  "全画面统一浅灰白色，人物为无五官无衣物细节的素模人偶，" +
  "场景为简化几何体块，均匀柔和的白色环境光，无色彩倾向";

const PREVIZ_HEADER = [
  "【渲染模式：白模预演】",
  "本次输出的是**分镜预演**，不是成片。整个画面必须是无材质的灰白模型：",
  "· 人物一律渲染成无五官、无发丝、无衣物细节的浅灰色素模人偶，只保留身形比例与姿态；",
  "· 场景一律简化为浅灰白色几何体块，只保留空间结构与遮挡关系；",
  "· 全画面统一为浅灰白色，无贴图、无纹理、无色彩倾向、无氛围光效、无粒子与特效；",
  "· 光照只用均匀柔和的白色环境光，仅用于交代体积，不做任何戏剧性布光。",
  "",
  "**必须精确执行**的只有三件事：摄影机的机位与运动路径、景别的变化、角色在画面中的走位与姿态时序。",
  "",
  "",
].join("\n");

const PREVIZ_FOOTER = [
  "",
  "【再次确认渲染模式】",
  "以上正文里出现的一切材质、颜色、光影、氛围、表情与情绪描写，本次**一律忽略**，",
  "只按它们推断出的空间位置、姿态与时间节奏来运动。",
  "输出必须是纯灰白无材质的素模画面（clay render），不得出现任何贴图、颜色或戏剧光效。",
].join("\n");

/**
 * 把正式视频提示词包成白模预演提示词。
 *
 * @param basePrompt 正常流程产出的完整视频提示词（已含参考定义段与分镜正文）
 */
export function wrapAsPrevizPrompt(basePrompt: string): string {
  return `${PREVIZ_HEADER}${basePrompt}${PREVIZ_FOOTER}`;
}

function staticState(state) {
  return STATIC_STATE_REWRITES.get(state) ?? state;
}

function effectFor(owner, action) {
  if (COMBAT_RE.test(action)) return `${owner}沿原发力方向收势，衣摆与武器余振逐渐减弱`;
  if (MOVE_RE.test(action)) return `${owner}把重心移到前脚，后侧衣摆随惯性回落`;
  if (MAGIC_RE.test(action)) return `${owner}保持指尖与法器同轴，灵光向目标位置收束`;
  if (GAZE_RE.test(action)) return `${owner}眼睑停止细颤，视线在目标位置锁定`;
  if (/握|按|扣|扶|抱|捧|接|递|摸|触/.test(action)) return `${owner}手指逐节收紧，肩线随手部动作移动`;
  if (GRIEF_RE.test(action)) return `${owner}喉结轻动，肩线随呼气向内收拢`;
  if (INTIMATE_RE.test(action)) return `${owner}指尖停顿半拍，随后缓慢放松`;
  return `${owner}调整脚下重心，呼吸带动肩线起伏一次`;
}

function orientationFor(actorNames, owner, action, end) {
  return actorNames.map((name, i) => {
    let direction;
    const text = `${action}${end}`;
    if (name === owner && /背对|远去|离开|上行|走向|踏上|冲入/.test(text)) direction = "背对镜头";
    else if (name === owner && /右侧|向右/.test(text)) direction = "3/4侧面朝右";
    else if (name === owner && /左侧|向左/.test(text)) direction = "3/4侧面朝左";
    else if (actorNames.length >= 2) direction = i % 2 === 0 ? "3/4侧面朝右" : "3/4侧面朝左";
    else if (COMBAT_RE.test(text) || MOVE_RE.test(text)) direction = "正侧面朝右";
    else direction = "3/4侧面朝右";
    if (actorNames.length >= 3 && direction !== "背对镜头") {
      return `${name}${direction.endsWith("朝右") ? "朝右" : "朝左"}`;
    }
    return `${name}${direction}`;
  }).join("；");
}

function motionCamera(camera) {
  return camera
    .replace("从平视中景缓慢推至近景", "平视中景慢推近景")
    .replace("低机位沿动作路径跟随", "低机位跟随动作")
    .replace("平视等速跟随主体位移", "平视等速跟移")
    .replace("缓慢环绕主体并落在中景", "慢速环绕并落于中景")
    .replace("从中景极慢推至面部近景", "中景极慢推至面部近景")
    .replace("中景静置后轻微前推", "中景固定后微推")
    .replace("从全景缓慢推至中景", "全景慢推至中景");
}

function frameComposition(actorNames, focus, state, scene, action, end, index, ending) {
  const shotSize = COMBAT_RE.test(`${action}${end}`)
    ? "全景/低角度"
    : actorNames.length > 1
      ? "中景/平视"
      : index % 3 === 0
        ? "近景/平视"
        : "中景/平视";
  const placement = actorNames.map((name, i) => `${name}位于${POSITIONS[i] ?? "画面后景"}`).join("，");
  return `${shotSize}：${placement}；${state}；${lightFor(scene, 0)}；${bodyCue(action, end, ending)}`;
}

function parseDialogue(text) {
  if (!text) return [];
  return text.split("；").map((v) => {
    const idx = v.indexOf(":");
    return idx < 0 ? ["旁白", v] : [v.slice(0, idx), v.slice(idx + 1)];
  });
}

function sensoryFor(sfx) {
  const musicLike = /BGM|配乐|背景音乐|弦乐|古琴|战鼓|笛音|长笛|木鱼/;
  return sfx.split("、").find((item) => item && !musicLike.test(item)) || "衣料摩擦声";
}

function shot({ ep, index, title, scene, actor, start, action, end, dialogue, sfx, second }) {
  const from = index * 15;
  const to = from + 15;
  const ts = (s) => `${Math.floor(s / 60)}:${String(s % 60).padStart(2, "0")}`;
  const vi = visual(actor, ep);
  const svi = videoVisual(actor, ep);
  const actorNames = actor.split("、");
  const subject = actionOwner(action, actorNames);
  const narratedAction = actionWithOwner(action, actorNames);
  const startStill = staticState(start);
  const endStill = staticState(end);
  const sensory = sensoryFor(sfx);
  const dialoguePairs = parseDialogue(dialogue);
  const camera = cameraFor(narratedAction, dialoguePairs.length, second);
  const motionCameraText = motionCamera(camera.cn);
  const orientation = orientationFor(actorNames, subject, narratedAction, end);
  const effect = effectFor(subject, narratedAction);
  let timeline;
  if (dialoguePairs.length >= 3) {
    const [d1, d2, d3] = dialoguePairs;
    timeline = `0-3s: [${svi}；${startStill}]；3-6s: [${narratedAction}，${motionCameraText}]；6-9s: [${d1[0]}（问）说：「${d1[1]}」]；9-12s: [${d2[0]}（答）说：「${d2[1]}」]；12-15s: [${d3[0]}（定）说：「${d3[1]}」，落幅：${endStill}]`;
  } else if (dialoguePairs.length === 2) {
    const [d1, d2] = dialoguePairs;
    timeline = `0-3s: [${svi}；${startStill}]；3-6s: [${narratedAction}，${motionCameraText}]；6-10s: [${d1[0]}（下颌轻动）说：「${d1[1]}」]；10-13s: [${d2[0]}（视线回应）说：「${d2[1]}」]；13-15s: [落幅：${endStill}，${sensory}清晰可闻]`;
  } else if (dialoguePairs.length === 1) {
    const [d] = dialoguePairs;
    timeline = `0-3s: [${svi}；${startStill}]；3-7s: [${narratedAction}，${motionCameraText}]；7-11s: [${d[0]}（下颌轻动）说：「${d[1]}」]；11-15s: [落幅：${endStill}，${sensory}清晰可闻]`;
  } else {
    timeline = `0-3s: [${svi}；${startStill}]；3-7s: [${narratedAction}，${motionCameraText}]；7-11s: [${effect}]；11-15s: [落幅：${endStill}，${sensory}清晰可闻]`;
  }
  const vs = `${timeline}。｜朝向：${orientation}`;
  const firstFrame = frameComposition(actorNames, subject, startStill, scene, narratedAction, endStill, index, false).replace(lightFor(scene, 0), lightFor(scene, ep));
  const lastFrame = frameComposition(actorNames, subject, endStill, scene, narratedAction, endStill, index, true).replace(lightFor(scene, 0), lightFor(scene, ep));
  const lines = [
    `#### ${ts(from)}-${ts(to)}|${title}`,
    "",
    `- **【背景音】** ${scoreFor(ep, scene, narratedAction, end)}`,
    `- **【运镜】** ${camera.en}`,
    `- **【画面】** ${vi}；${narratedAction}，由“${start}”落到“${end}”。`,
    `- **【首帧】** ${firstFrame}。`,
    `- **【尾帧】** ${lastFrame}。`,
    `- **【motionScript】** ${vs}`,
  ];
  for (const [name, value] of parseDialogue(dialogue)) lines.push(`- **【对白】** ${name}：『${value}』`);
  lines.push(`- **【音效】** ${sfx}`);
  return lines.join("\n");
}

function normalizeBeat(raw) {
  const p = raw.split("^");
  // 多于九格时，额外的连续动作合并进“动作二”，保留末尾的尾帧/对白/音效。
  while (p.length > 9) {
    p[5] = `${p[5]}并${p[6]}`;
    p.splice(6, 1);
  }
  // 部分紧凑数据将“动作二”同时作为尾帧，补齐尾帧槽位，避免对白/音效左移。
  if (p.length === 8) p.splice(6, 0, p[5]);
  while (p.length < 9) p.push("");
  if (p.length !== 9) throw new Error(`invalid beat fields (${p.length}): ${raw}`);
  return p;
}

